# -*- coding: utf-8 -*-

"""
Generate ``QUICK_LINKS.md``: the console of every AWS resource of this project,
one table per environment (``mise run gen-quick-links``).

What the config names is built from the local config files, with no AWS call:
every CDK stack, the AgentCore stack, the config parameter. What AWS names at
deploy time is looked up, read only, with the profile of each environment: per
runtime, its console page, its execution role, and its log group. A runtime
that is not deployed, or an environment whose runtimes cannot be read, says so
instead of a link.

The file holds no account ID: every link is built from a name or an ID.
"""

from __future__ import annotations

import typing as T
import os
import dataclasses
from pathlib import Path

import boto3

from ..env import EnvNameEnum
from ..paths import path_enum
from ..config.api import Config
from ..one.one_02_boto_ses import get_aws_profile_env_var
from ..cdk.mise_tasks import StackTarget
from ..cdk.mise_tasks import get_stack_targets
from ..agentcore_project.registry import RuntimeSpec
from ..agentcore_project.registry import get_runtime_specs
from .agentcore_client import DeployedRuntime
from .agentcore_client import find_deployed_runtimes
from .agentcore_client import get_runtime_log_group

HEADER = """\
# Quick Links

The console of every AWS resource of this project, by environment.
Sign in to the account of an environment before opening its links.

Generated by `mise run gen-quick-links`: the stacks and the config parameter
from `config/`, the runtimes, their roles, and their logs looked up in AWS with
the profile of each environment. Do not edit by hand.
"""

TABLE_HEADER = ["| Resource | Console |", "| :--- | :--- |"]


@dataclasses.dataclass(frozen=True)
class QuickLink:
    """
    One row of a table: a resource, its name, and its console URL (``None``
    when there is no page to link, such as a runtime not deployed).
    """

    # fmt: off
    resource: str = dataclasses.field()  #: What it is, such as ``IAM role, MyAgent``.
    name: str = dataclasses.field()  #: Its name or ID, shown as code.
    url: str | None = dataclasses.field(default=None)  #: Its console page.
    note: str = dataclasses.field(default="")  #: Shown after the name when there is no URL.
    # fmt: on

    def to_row(self) -> str:
        """
        The Markdown table row.
        """
        if self.url is None:
            return f"| {self.resource} | `{self.name}`: {self.note} |"
        return f"| {self.resource} | [`{self.name}`]({self.url}) |"


def get_config_links(
    config: Config,
    stack_targets: dict[str, StackTarget],
) -> list[QuickLink]:
    """
    The links the config names: every CDK stack, the AgentCore stack, and the
    config parameter.
    """
    links = [
        QuickLink(
            resource=f"CloudFormation stack, {stack}",
            name=target.construct_id,
            url=target.console_url,
        )
        for stack, target in stack_targets.items()
    ]
    links.append(
        QuickLink(
            resource="CloudFormation stack, AgentCore runtimes",
            name=config.cft_stack_name_agentcore,
            url=config.cft_stack_url_agentcore,
        )
    )
    links.append(
        QuickLink(
            resource="SSM parameter, config",
            name=config.ssm_param_name_config,
            url=config.ssm_param_url_config,
        )
    )
    return links


def get_runtime_links(
    config: Config,
    spec: RuntimeSpec,
    deployed: DeployedRuntime | None,
    note: str = "not deployed",
) -> list[QuickLink]:
    """
    The links of one runtime: its console page, its execution role, and its
    log group; or one row with ``note`` when it is not deployed.
    """
    if deployed is None:
        physical_name = config.get_agentcore_runtime_physical_name(spec.name)
        return [
            QuickLink(
                resource=f"AgentCore runtime, {spec.name}",
                name=physical_name,
                note=note,
            )
        ]
    log_group = get_runtime_log_group(deployed.runtime_arn)
    return [
        QuickLink(
            resource=f"AgentCore runtime, {spec.name}",
            name=deployed.runtime_id,
            url=config.get_agentcore_runtime_url(deployed.runtime_id),
        ),
        QuickLink(
            resource=f"IAM role, {spec.name} execution",
            name=deployed.role_name,
            url=config.get_iam_role_url(deployed.role_name),
        ),
        QuickLink(
            resource=f"CloudWatch log group, {spec.name}",
            name=log_group,
            url=config.get_cloudwatch_log_group_url(log_group),
        ),
    ]


def get_env_links(
    config: Config,
    stack_targets: dict[str, StackTarget],
    specs: list[RuntimeSpec],
    deployed: dict[str, DeployedRuntime] | Exception,
) -> list[QuickLink]:
    """
    Every link of one environment.

    :param deployed: from :func:`find_deployed_runtimes`, by physical name; or
        the error that stopped reading them, so each runtime says it was not read.
    """
    links = get_config_links(config, stack_targets)
    for spec in specs:
        if isinstance(deployed, Exception):
            # only the type: the message may hold a local path or an account ID
            note = f"not read ({type(deployed).__name__})"
            links.extend(get_runtime_links(config, spec, None, note=note))
        else:
            physical_name = config.get_agentcore_runtime_physical_name(spec.name)
            links.extend(get_runtime_links(config, spec, deployed.get(physical_name)))
    return links


def render_quick_links(sections: dict[str, list[QuickLink] | Exception]) -> str:
    """
    The whole file: one table per environment, or an error line for an
    environment whose config does not load.
    """
    lines = [HEADER.rstrip("\n")]
    for env_name, links in sections.items():
        lines += ["", f"## {env_name}", ""]
        if isinstance(links, Exception):
            lines.append(
                f"ERROR: cannot load the config of `{env_name}`: `{type(links).__name__}`."
            )
        else:
            lines += TABLE_HEADER + [link.to_row() for link in links]
    return "\n".join(lines) + "\n"


def get_env_boto_session(config: Config) -> boto3.Session:
    """
    A boto3 session of the environment of ``config``: its local profile
    ``AWS_PROFILE_FOR_<ENV>`` when set, its region.
    """
    profile_name = os.environ.get(get_aws_profile_env_var(config.env_name)) or None
    return boto3.Session(profile_name=profile_name, region_name=config.aws_region)


def read_deployed_runtimes(
    config: Config,
    specs: list[RuntimeSpec],
) -> dict[str, DeployedRuntime] | Exception:
    """
    The deployed runtimes of the environment of ``config``, read with its
    profile; the error instead if they cannot be read (no profile, no access).
    """
    physical_names = [
        config.get_agentcore_runtime_physical_name(spec.name) for spec in specs
    ]
    try:
        control_client = get_env_boto_session(config).client(
            "bedrock-agentcore-control"
        )
        return find_deployed_runtimes(control_client, physical_names)
    except Exception as e:
        return e


def generate_quick_links(
    path: Path,
    read: T.Callable[[Config, list[RuntimeSpec]], dict | Exception] | None = None,
) -> bool:
    """
    Write ``QUICK_LINKS.md`` at ``path`` for every environment, only if it
    changed; print what happened per environment.

    :param read: reads the deployed runtimes of one environment;
        :func:`read_deployed_runtimes` when ``None``.

    :returns: ``True`` if the file changed.
    """
    if read is None:
        read = read_deployed_runtimes
    sections = {}
    for member in EnvNameEnum:
        env_name = member.value
        try:
            config = Config.load_from_local_config_file(env_name=env_name)
        except Exception as e:
            print(f"{env_name}: ERROR: cannot load the config: {type(e).__name__}")
            sections[env_name] = e
            continue
        specs = get_runtime_specs(config)
        deployed = read(config, specs)
        if isinstance(deployed, Exception):
            print(f"{env_name}: runtimes not read: {type(deployed).__name__}")
        else:
            print(f"{env_name}: {len(deployed)} of {len(specs)} runtimes deployed")
        sections[env_name] = get_env_links(
            config, get_stack_targets(env_name), specs, deployed
        )
    text = render_quick_links(sections)
    if path.exists() and path.read_text(encoding="utf-8") == text:
        print(f"{path} is already up to date")
        return False
    path.write_text(text, encoding="utf-8")
    print(f"Updated {path}")
    return True


def main() -> None:
    """
    :func:`generate_quick_links` into ``QUICK_LINKS.md`` at the repo root.
    """
    generate_quick_links(path_enum.path_quick_links_md)
