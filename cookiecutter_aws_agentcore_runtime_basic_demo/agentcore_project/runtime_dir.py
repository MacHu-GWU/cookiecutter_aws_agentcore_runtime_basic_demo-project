# -*- coding: utf-8 -*-

"""
Assemble the code directory (``codeLocation``) of a runtime, ``app/<Runtime>/``,
which ``agentcore build`` / ``agentcore deploy`` zip:

- ``main.py``: a shim that calls ``main()`` of the runtime module.
- ``pyproject.toml``: ``[project].dependencies`` = the ``agentcore`` dependency group,
  pinned by ``uv.lock``. The CLI installs only this list and ignores ``uv.lock``.
- a copy of the package, only the subpackages the runtimes need, which never import
  config, ``one``, or cdk.

The directory is a build output (git-ignored); the package and ``uv.lock`` stay the
only sources of code and dependencies.
"""

from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path

from ..paths import PACKAGE_NAME
from ..paths import path_enum

#: Subpackages copied into every runtime; everything they import must be in this list.
RUNTIME_SUBPACKAGES = ["power_plant", "runtimes"]

#: ``main.py`` of a runtime; the CLI and AgentCore Runtime run it as a script.
MAIN_PY = """# Generated by `mise run ac-gen`; do not edit.
from {package}.{module} import main

main()
"""


def export_requirements() -> list[str]:
    """
    The ``agentcore`` dependency group with every transitive dependency, pinned
    by ``uv.lock``, one requirement per item (markers kept).
    """
    args = [
        "uv",
        "export",
        "--frozen",
        "--only-group",
        "agentcore",
        "--no-emit-project",
        "--no-hashes",
        "--no-annotate",
        "--no-header",
    ]
    result = subprocess.run(
        args,
        cwd=path_enum.dir_project_root,
        capture_output=True,
        text=True,
        check=True,
    )
    requirements = []
    for line in result.stdout.splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            requirements.append(line)
    return requirements


def render_pyproject_toml(name: str, requirements: list[str]) -> str:
    """
    The ``pyproject.toml`` of a runtime.
    """
    lines = [
        "# Generated by `mise run ac-gen` from uv.lock; do not edit.",
        "[project]",
        f'name = "{name.lower()}"',
        'version = "0.1.0"',
        "dependencies = [",
    ]
    for requirement in requirements:
        # a JSON string is a valid TOML basic string
        lines.append(f"    {json.dumps(requirement)},")
    lines.append("]")
    return "\n".join(lines) + "\n"


def assemble_runtime_dir(
    dir_runtime: Path,
    name: str,
    module: str,
    requirements: list[str],
) -> None:
    """
    Recreate ``dir_runtime`` from scratch.

    :param name: the runtime name in ``agentcore.json``.
    :param module: the runtime module relative to the package, such as ``runtimes.site_agent``.
    :param requirements: from :func:`export_requirements`.
    """
    shutil.rmtree(dir_runtime, ignore_errors=True)
    dir_package = dir_runtime / PACKAGE_NAME
    dir_package.mkdir(parents=True)
    main_py = MAIN_PY.format(package=PACKAGE_NAME, module=module)
    (dir_runtime / "main.py").write_text(main_py, encoding="utf-8")
    pyproject_toml = render_pyproject_toml(name, requirements)
    (dir_runtime / "pyproject.toml").write_text(pyproject_toml, encoding="utf-8")
    shutil.copy(path_enum.dir_package / "__init__.py", dir_package / "__init__.py")
    for subpackage in RUNTIME_SUBPACKAGES:
        shutil.copytree(
            path_enum.dir_package / subpackage,
            dir_package / subpackage,
            ignore=shutil.ignore_patterns("__pycache__"),
        )
