# -*- coding: utf-8 -*-

"""
Package each runtime as a CodeZip: assemble its code directory
(``codeLocation``), ``app/<Runtime>/``, which ``agentcore build`` and
``agentcore deploy`` zip, and check that its dependencies install the way the
CLI installs them.

``app/<Runtime>/`` holds:

- ``main.py``: a shim that imports and calls ``main()`` of the runtime module
  (and exposes ``app`` for an ``HTTP`` runtime).
- ``pyproject.toml``: ``[project].dependencies`` = the ``agentcore`` dependency
  group, every version pinned from ``uv.lock``: the CLI installs only this list
  and ignores ``uv.lock``.
- a copy of only the modules and subpackages the runtimes need: never ``cdk/``,
  ``agentcore_project/``, or ``devtools/``, which run on the dev machine only.

The directory is a build output (git-ignored); the package and ``uv.lock`` stay
the only sources of code and dependencies.
"""

from __future__ import annotations

import sys
import json
import shutil
import tempfile
import subprocess
from pathlib import Path

from ..paths import PACKAGE_NAME
from ..paths import path_enum
from .registry import RUNTIME_PYTHON
from .registry import RuntimeProtocolEnum

#: Top-level modules of the package copied into every runtime.
RUNTIME_MODULES = ["__init__.py", "constants.py", "env.py", "paths.py", "runtime.py"]

#: Subpackages copied into every runtime. Everything the copied code imports at
#: module level must be copied too, or be in the ``agentcore`` dependency group;
#: ``one`` imports its CDK and dev-only dependencies inside functions.
RUNTIME_SUBPACKAGES = ["config", "one", "power_plant", "runtimes"]

#: ``main.py`` of a runtime. AgentCore Runtime runs it as a script (``python main.py``);
#: ``agentcore dev`` does too for an MCP server, but serves an agent (protocol ``HTTP``)
#: with ``uvicorn main:app``, so the agent's shim also exposes ``app``.
MAIN_PY = """# Generated by `mise run ac-gen`; do not edit.
{imports}

if __name__ == "__main__":
    main()
"""


#: The platforms the AgentCore CLI 1.0.1 tries, in order, to install the
#: dependencies of a CodeZip runtime (``PLATFORM_CANDIDATES`` in
#: ``@aws/agentcore-cdk``, ``lib/packaging/python.js``); the first that works wins.
CODEZIP_PLATFORMS = [
    "aarch64-manylinux2014",
    "aarch64-manylinux_2_28",
    "aarch64-manylinux_2_34",
]


def check_codezip_install(path_pyproject_toml: Path) -> str | None:
    """
    Install the dependencies of a runtime the way ``agentcore deploy`` packages
    a CodeZip (wheels only, for Linux aarch64), into a temporary directory.
    The CLI then reports only "uv install failed for all platform candidates";
    this keeps uv's own message, such as which package has no wheel.

    :returns: ``None`` if one of :data:`CODEZIP_PLATFORMS` works, else the uv
        output of the last one.
    """
    output = ""
    for platform in CODEZIP_PLATFORMS:
        with tempfile.TemporaryDirectory() as dir_target:
            args = [
                "uv",
                "pip",
                "install",
                "-r",
                str(path_pyproject_toml),
                "--target",
                dir_target,
                "--python-version",
                RUNTIME_PYTHON,
                "--python-platform",
                platform,
                "--only-binary",
                ":all:",
                "--dry-run",
                # any interpreter: the version and platform above are the target
                "--python",
                sys.executable,
            ]
            result = subprocess.run(args, capture_output=True, text=True)
        if result.returncode == 0:
            return None
        output = f"{platform}:\n{result.stdout}{result.stderr}"
    return output


def export_requirements() -> list[str]:
    """
    The ``agentcore`` dependency group with every transitive dependency, pinned
    by ``uv.lock``, one requirement per item (markers kept).
    """
    args = [
        "uv",
        "export",
        "--frozen",
        "--only-group",
        "agentcore",
        "--no-emit-project",
        "--no-hashes",
        "--no-annotate",
        "--no-header",
    ]
    result = subprocess.run(
        args,
        cwd=path_enum.dir_project_root,
        capture_output=True,
        text=True,
        check=True,
    )
    requirements = []
    for line in result.stdout.splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            requirements.append(line)
    return requirements


def render_pyproject_toml(name: str, requirements: list[str]) -> str:
    """
    The ``pyproject.toml`` of a runtime.
    """
    lines = [
        "# Generated by `mise run ac-gen` from uv.lock; do not edit.",
        "[project]",
        f'name = "{name.lower()}"',
        'version = "0.1.0"',
        f'requires-python = ">={RUNTIME_PYTHON}"',
        "dependencies = [",
    ]
    for requirement in requirements:
        # a JSON string is a valid TOML basic string
        lines.append(f"    {json.dumps(requirement)},")
    lines.append("]")
    return "\n".join(lines) + "\n"


def assemble_runtime_dir(
    dir_runtime: Path,
    name: str,
    module: str,
    protocol: RuntimeProtocolEnum,
    requirements: list[str],
) -> None:
    """
    Write ``main.py``, ``pyproject.toml``, and a fresh copy of the package into
    ``dir_runtime``. Anything else there is left alone, such as the ``.venv`` and
    ``uv.lock`` of ``agentcore dev``, so a running dev server keeps working.

    :param name: the runtime name in ``agentcore.json``.
    :param module: the runtime module relative to the package, such as ``runtimes.site_agent``;
        it has a ``main()``, and an ``app`` if ``protocol`` is ``HTTP``.
    :param protocol: how AgentCore talks to the runtime.
    :param requirements: from :func:`export_requirements`.
    """
    dir_package = dir_runtime / PACKAGE_NAME
    shutil.rmtree(dir_package, ignore_errors=True)
    dir_package.mkdir(parents=True)
    imported_names = ["main"]
    if protocol == RuntimeProtocolEnum.HTTP:
        imported_names.append("app")
    imports = []
    for imported_name in imported_names:
        imports.append(f"from {PACKAGE_NAME}.{module} import {imported_name}")
    main_py = MAIN_PY.format(imports="\n".join(imports))
    (dir_runtime / "main.py").write_text(main_py, encoding="utf-8")
    pyproject_toml = render_pyproject_toml(name, requirements)
    (dir_runtime / "pyproject.toml").write_text(pyproject_toml, encoding="utf-8")
    for module_name in RUNTIME_MODULES:
        shutil.copy(path_enum.dir_package / module_name, dir_package / module_name)
    for subpackage in RUNTIME_SUBPACKAGES:
        shutil.copytree(
            path_enum.dir_package / subpackage,
            dir_package / subpackage,
            ignore=shutil.ignore_patterns("__pycache__"),
        )


def check_codezip_installs(dir_app: Path) -> bool:
    """
    :func:`check_codezip_install` for every runtime in ``dir_app`` (``app/``,
    written by ``mise run ac-gen``), printing ``OK`` or uv's error for each.

    :returns: ``True`` if every runtime's dependencies install.
    """
    ok = True
    for path in sorted(dir_app.glob("*/pyproject.toml")):
        error = check_codezip_install(path)
        if error is None:
            print(
                f"OK: the dependencies of {path.parent.name} have Linux aarch64 wheels"
            )
        else:
            print(f"ERROR: the dependencies of {path.parent.name} do not install:")
            print(error)
            ok = False
    return ok
