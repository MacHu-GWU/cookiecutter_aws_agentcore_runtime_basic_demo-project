import { AgentCoreApplication, type AgentCoreApplicationProps } from '@aws/agentcore-cdk';
import { Stack, type StackProps } from 'aws-cdk-lib';
import { Construct } from 'constructs';

export interface AgentCoreStackProps extends StackProps {
  /** Props for the AgentCore application, produced by transformAgentCoreJson from agentcore/agentcore.json. */
  application: AgentCoreApplicationProps;
}

/**
 * The stack the AgentCore CLI deploys. Everything declared in agentcore/agentcore.json is
 * created by the AgentCoreApplication construct. Add your own resources below it and wire
 * them to your runtimes and harnesses through the application's accessors.
 */
export class AgentCoreStack extends Stack {
  public readonly application: AgentCoreApplication;

  constructor(scope: Construct, id: string, props: AgentCoreStackProps) {
    super(scope, id, props);
    this.application = new AgentCoreApplication(this, 'Application', props.application);

    // The agent calls the MCP server with SigV4 (AWS_IAM): bind() grants the agent's role
    // bedrock-agentcore:InvokeAgentRuntime on the MCP runtime and sets the agent's env var
    // AGENTCORE_RUNTIME_POWERPLANTMCP_ARN to its ARN. The runtime names come from
    // agentcore.json, generated from the config (agentcore_runtime_name_* in config_01_name.py).
    // An empty project (`mise run ac-down-<env>`) declares no runtime, and must still synthesize.
    if (this.application.runtimes.size > 0) {
      this.application.runtime('PowerPlantMcp').bind(this.application.runtime('SiteAgent'));
    }

    // Only AgentCore wiring belongs here. What the runtimes use but is not AgentCore
    // (IAM policies, databases, buckets, ...) is deployed by the agentcore_deps CDK stack
    // (cookiecutter_aws_agentcore_runtime_basic_demo/cdk/stacks/agentcore_deps_stack.py)
    // and referred to by name in agentcore.json, generated by `mise run ac-gen`:
    // `additionalPolicies` on the execution role, `envVars`, and later `networkConfig`.
  }
}
